import fs from 'node:fs';
import path from 'node:path';

const distDir = path.resolve('dist');
const docsDir = path.resolve('docs');
const distAssetsDir = path.join(distDir, 'assets');

// Remove dev-only attachment folder from dist before deploying
fs.rmSync(path.join(distAssetsDir, 'aistudio'), { recursive: true, force: true });

// Sync dist -> docs for GitHub Pages (/docs branch mode)
fs.rmSync(docsDir, { recursive: true, force: true });
fs.cpSync(distDir, docsDir, { recursive: true });

// Discover compiled bundle filenames in dist/assets
const assetFiles = fs.existsSync(distAssetsDir) ? fs.readdirSync(distAssetsDir) : [];
const cssFiles = assetFiles.filter((f) => f.endsWith('.css')).sort();
const jsFiles = assetFiles.filter((f) => f.endsWith('.js')).sort();

// Generate docs/boot.js so GitHub Pages root (/) mode loads exact compiled bundles cleanly
const bootScript = `// Auto-generated by npm run build for GitHub Pages root (/) compatibility
(function () {
  var scriptEl = document.currentScript;
  var base = scriptEl && scriptEl.src ? new URL('./', scriptEl.src).href : './docs/';
  var cssFiles = ${JSON.stringify(cssFiles)};
  var jsFiles = ${JSON.stringify(jsFiles)};
  cssFiles.forEach(function (file) {
    var link = document.createElement('link');
    link.rel = 'stylesheet';
    link.crossOrigin = 'anonymous';
    link.href = base + 'assets/' + file;
    document.head.appendChild(link);
  });
  jsFiles.forEach(function (file) {
    var mod = document.createElement('script');
    mod.type = 'module';
    mod.crossOrigin = 'anonymous';
    mod.src = base + 'assets/' + file;
    document.body.appendChild(mod);
  });
})();
`;

fs.writeFileSync(path.join(docsDir, 'boot.js'), bootScript, 'utf8');
console.log('[KUBER] Synced dist/ and docs/ with boot.js:', { cssFiles, jsFiles });
